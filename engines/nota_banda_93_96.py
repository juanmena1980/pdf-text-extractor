def _pattern(src: tuple[str, ...], where: str) -> re.Pattern[str]:
    body = r"\s+".join(re.escape(part) for part in src)
    if where == "start":
        return re.compile(rf"^\s*{body}(?!\S)")
    if where == "end":
        return re.compile(rf"(?<!\S){body}\s*$")
    return re.compile(rf"(?<!\S){body}(?!\S)")


_COMPILED = tuple(
    (" ".join(src), _pattern(src, where), " ".join(dst))
    for src, dst, where in RULES
)


def apply_banda_93_96(text: str) -> str:
    """Aplica las correcciones aprendidas en la franja 93-96."""
    flat = re.sub(r"\s+", " ", text)
    changed = False
    for needle, pattern, replacement in _COMPILED:
        if needle not in flat:
            continue
        updated = pattern.sub(replacement, text, count=1)
        if updated == text:
            continue
        text = updated
        changed = True
        flat = re.sub(r"\s+", " ", text)
    if not changed:
        return text
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = re.sub(r" *\n *", "\n", text)
    return text.strip()
